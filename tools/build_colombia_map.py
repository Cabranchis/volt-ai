"""Turn a GeoJSON of Colombia's departments into the SVG paths the map page draws.

The page needs no map library: this script projects the outlines once (equirectangular, 100 units
per degree of latitude), thins them with Douglas-Peucker and writes web/src/lib/geo/colombia.ts.

Usage:
    python tools/build_colombia_map.py path/to/Colombia.geo.json

The source file is the department boundaries of DANE's Marco Geoestadístico Nacional, as
republished at https://gist.github.com/john-guerra/43c7656821069d00dcbc (CRS84, features carry
DPTO and NOMBRE_DPT). San Andrés y Providencia is left out: it lies 700 km from the mainland and
has no reservoir. Standard library only.
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "web" / "src" / "lib" / "geo" / "colombia.ts"
SCALE = 100.0  # units per degree
TOLERANCE = 0.012  # degrees, about 1.3 km
SKIP = {"88"}  # San Andrés y Providencia
NAMES = {  # the source mangles some accents
    "05": "Antioquia", "08": "Atlántico", "11": "Bogotá D.C.", "13": "Bolívar", "15": "Boyacá",
    "17": "Caldas", "18": "Caquetá", "19": "Cauca", "20": "Cesar", "23": "Córdoba",
    "25": "Cundinamarca", "27": "Chocó", "41": "Huila", "44": "La Guajira", "47": "Magdalena",
    "50": "Meta", "52": "Nariño", "54": "Norte de Santander", "63": "Quindío", "66": "Risaralda",
    "68": "Santander", "70": "Sucre", "73": "Tolima", "76": "Valle del Cauca", "81": "Arauca",
    "85": "Casanare", "86": "Putumayo", "91": "Amazonas", "94": "Guainía", "95": "Guaviare",
    "97": "Vaupés", "99": "Vichada",
}  # fmt: skip

Point = tuple[float, float]


def rings(geometry: dict) -> list[list[Point]]:
    polygons = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
    return [[(p[0], p[1]) for p in ring] for polygon in polygons for ring in polygon]


def simplify(points: list[Point], tolerance: float) -> list[Point]:
    """Douglas-Peucker, iterative so long rings do not hit the recursion limit."""
    if len(points) < 4:
        return points
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        first, last = stack.pop()
        (x1, y1), (x2, y2) = points[first], points[last]
        dx, dy = x2 - x1, y2 - y1
        norm = math.hypot(dx, dy)
        far, index = 0.0, -1
        for i in range(first + 1, last):
            x, y = points[i]
            d = abs(dy * (x - x1) - dx * (y - y1)) / norm if norm else math.hypot(x - x1, y - y1)
            if d > far:
                far, index = d, i
        if far > tolerance and index >= 0:
            keep[index] = True
            stack += [(first, index), (index, last)]
    return [p for p, k in zip(points, keep, strict=True) if k]


def main(source: str) -> None:
    features = json.loads(Path(source).read_text(encoding="utf-8"))["features"]
    kept = [f for f in features if f["properties"]["DPTO"] not in SKIP]
    all_points = [p for f in kept for ring in rings(f["geometry"]) for p in ring]
    lon_min, lon_max = min(p[0] for p in all_points), max(p[0] for p in all_points)
    lat_min, lat_max = min(p[1] for p in all_points), max(p[1] for p in all_points)
    lat_mid = math.radians((lat_min + lat_max) / 2)
    pad = 0.4  # degrees around the country
    lon0, lat0 = lon_min - pad, lat_max + pad
    kx = SCALE * math.cos(lat_mid)

    def project(point: Point) -> tuple[float, float]:
        return (point[0] - lon0) * kx, (lat0 - point[1]) * SCALE

    width = (lon_max + pad - lon0) * kx
    height = (lat0 - (lat_min - pad)) * SCALE
    departments = []
    for feature in sorted(kept, key=lambda f: f["properties"]["DPTO"]):
        code = feature["properties"]["DPTO"]
        parts = []
        for ring in rings(feature["geometry"]):
            thin = simplify(ring, TOLERANCE)
            if len(thin) < 4:
                continue
            xy = [project(p) for p in thin]
            parts.append("M" + "L".join(f"{x:.1f} {y:.1f}" for x, y in xy) + "Z")
        departments.append({"code": code, "name": NAMES[code], "path": "".join(parts)})

    body = json.dumps(departments, ensure_ascii=False, indent=2)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by tools/build_colombia_map.py from the DANE department boundaries. Do not edit.\n"
        "// Equirectangular projection: x = (lon - lon0) * kx, y = (lat0 - lat) * scale.\n\n"
        f"export const PROJECTION = {{ lon0: {lon0:.4f}, lat0: {lat0:.4f}, kx: {kx:.4f}, scale: {SCALE:.1f} }} as const;\n"
        f"export const MAP_SIZE = {{ width: {width:.1f}, height: {height:.1f} }} as const;\n\n"
        "export interface Department {\n  code: string;\n  name: string;\n  path: string;\n}\n\n"
        f"export const DEPARTMENTS: readonly Department[] = {body};\n",
        encoding="utf-8",
    )
    size = OUT.stat().st_size
    print(f"wrote {OUT} ({size / 1024:.0f} KB), {len(departments)} departments, {width:.0f} x {height:.0f}")


if __name__ == "__main__":
    main(sys.argv[1])
